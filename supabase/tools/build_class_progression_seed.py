#!/usr/bin/env python3
"""Build only this release's delta. Does not connect to a live database."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACK = json.loads((ROOT/'narrative/class_progression_pack.json').read_text())
JSON_FIELDS={'base_stats_bonus','learnable_skill_ids','quest_giver','requirements','objectives','rewards','equipment_slots','stats_bonus','special_effects','available_services','actions','nodes','stat_modifiers','periodic_effects','control_effects','usage_requirements','element','spawn_location','base_stats','scaling','resistances','weaknesses','status_immunity','ai_pattern','skill_set','drop_item','special_reward'}


def literal(value, col):
    if value is None: return 'null'
    if col in JSON_FIELDS:
        return "'"+json.dumps(value,ensure_ascii=False).replace("'","''")+"'::jsonb"
    if isinstance(value,bool): return str(value).lower()
    if isinstance(value,(int,float)): return str(value)
    return "'"+str(value).replace("'","''")+"'"


def upsert(table, rows, columns, key, transform=lambda r:r):
    out=[]
    for order, original in enumerate(rows):
        row=transform(original.copy());row.setdefault('sort_order',10000+order)
        used=[c for c in columns if c in row]
        out.append('insert into public.'+table+' ('+', '.join('"'+c+'"' for c in used)+') values ('+', '.join(literal(row[c],c) for c in used)+')\non conflict ('+key+') do update set '+', '.join('"'+c+'"=excluded."'+c+'"' for c in used if c!=key and c not in ('is_active','emergency_blocked','content_revision'))+';')
    return '\n'.join(out)


def class_row(row):
    row['is_active']=row.pop('isActive'); return row


def quest_row(row):
    row['source_file']='quest_list.json'; return row


def dialog_row(row):
    row['source_file']='dialog_quests.json'; return row


def main():
    parts=['-- Generated by build_class_progression_seed.py. Prepared only; no player rows modified.','begin;',
           '-- Retire definitions, retaining saved player progress and inventory.',
           'delete from public.dialogs where quest_id in ('+', '.join(literal(x,'') for x in PACK['retired_quests'])+');',
           'delete from public.quests where id in ('+', '.join(literal(x,'') for x in PACK['retired_quests'])+');']
    specs=[
      ('classes',PACK['classes'],['id','name','tier','parent_id','description','is_active','base_stats_bonus','learnable_skill_ids','sort_order'],'id',class_row),
      ('items',PACK['items'],['id','name','type','rarity','level_requirement','buy_price','sell_price','max_stack','icon_image','description','equipment_slots','stats_bonus','special_effects','sort_order'],'id',lambda r:r),
      ('npcs',PACK['npcs'],['npc_id','name','title','role','faction','location','region_id','description','personality','greeting','dialogue_tree','shop_inventory','available_services','actions','sort_order'],'npc_id',lambda r:r),
      ('quests',PACK['quests'],['id','title','type','rank','faction','region','description','quest_giver','requirements','objectives','rewards','repeatable','daily','auto_accept','quest_chain_next','source_file','sort_order'],'id',quest_row),
      ('dialogs',PACK['dialogs'],['dialog_id','quest_id','npc_id','start_node','nodes','source_file','sort_order'],'dialog_id',dialog_row),
      ('skills',PACK.get('skills',[]),['id','name','type','source_type','mp_cost','damage_formula','effect','skill_description','skill_shape','range','aoe_radius','projectile_speed','cooldown_seconds','arc_angle_degrees','target_attack','target_effect','stat_modifiers','periodic_effects','control_effects','special_effects','usage_requirements','sort_order'],'id',lambda r:r),
    ]
    parts += [upsert(*spec) for spec in specs]
    # Fill a missing target definition without changing existing enemy balance.
    monster_cols=['monster_id','code','name','rank','level','race_code','spawn_monster_id','critical_rate','critical_damage','exp_reward','currency_reward','crd_reward','guild_point','reputation_point','hunting_point','element','spawn_location','base_stats','scaling','resistances','weaknesses','status_immunity','ai_pattern','skill_set','drop_item','special_reward','sort_order']
    import re
    missing_monsters=upsert('monsters',PACK['monsters'],monster_cols,'monster_id')
    missing_monsters=re.sub(r'on conflict \(monster_id\) do update set [^\n]+;', 'on conflict (monster_id) do nothing;', missing_monsters)
    parts.append(missing_monsters)
    parts.append('commit;')
    target=ROOT/'supabase/seed/class_progression_20261008.sql';target.write_text('\n\n'.join(parts)+'\n')
    print('Prepared',target,'with',[(s[0],len(s[1])) for s in specs])


if __name__=='__main__': main()
