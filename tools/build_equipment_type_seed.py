#!/usr/bin/env python3
"""Generate a guarded, idempotent type-only seed for existing public.items."""
import json

from migrate_equipment_types import EXPLICIT, ROOT


def build_sql():
    payload = json.dumps([{'id': key, 'type': value} for key, value in EXPLICIT.items()])
    return f"""-- Generated by tools/build_equipment_type_seed.py. Existing items only.
-- Preserves every business field except type; timestamp/version triggers remain enabled.
BEGIN;
DO $seed$
DECLARE
  desired jsonb := $mapping${payload}$mapping$::jsonb;
  before_data jsonb;
  after_data jsonb;
  found_count integer;
BEGIN
  PERFORM i.id FROM public.items i
  JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id
  ORDER BY i.id FOR UPDATE OF i;
  SELECT count(*) INTO found_count FROM public.items i
  JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id;
  IF found_count <> jsonb_array_length(desired) THEN
    RAISE EXCEPTION 'Equipment seed aborted: missing expected item IDs';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.items i
    JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id
    WHERE i.type NOT IN (d.type,split_part(d.type,'_',1)) OR i.type IS NULL
  ) THEN
    RAISE EXCEPTION 'Equipment seed aborted: unexpected current subtype';
  END IF;
  SELECT jsonb_agg(to_jsonb(i)-'type'-'updated_at' ORDER BY i.id) INTO before_data
  FROM public.items i
  JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id;
  IF EXISTS (SELECT 1 FROM public.items i
    JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id
    WHERE i.type IS DISTINCT FROM d.type) THEN
    UPDATE public.items i SET type=d.type
    FROM jsonb_to_recordset(desired) AS d(id text,type text)
    WHERE i.id=d.id AND i.type IS DISTINCT FROM d.type;
  END IF;
  SELECT jsonb_agg(to_jsonb(i)-'type'-'updated_at' ORDER BY i.id) INTO after_data
  FROM public.items i
  JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id;
  IF before_data IS DISTINCT FROM after_data THEN
    RAISE EXCEPTION 'Equipment seed aborted: non-type business fields changed';
  END IF;
  IF EXISTS (SELECT 1 FROM public.items i
    JOIN jsonb_to_recordset(desired) AS d(id text,type text) ON d.id=i.id
    WHERE i.type IS DISTINCT FROM d.type) THEN
    RAISE EXCEPTION 'Equipment seed aborted: final subtype mismatch';
  END IF;
END;
$seed$;
COMMIT;
SELECT type,count(*) AS item_count FROM public.items
WHERE type LIKE 'WEAPON\\_%' ESCAPE '\\' OR type LIKE 'ACCESSORY\\_%' ESCAPE '\\'
GROUP BY type ORDER BY type;
"""


if __name__ == '__main__':
    path = ROOT / 'supabase' / 'seed' / 'equipment_type_subtypes.sql'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_sql())
    print(f'Generated {len(EXPLICIT)} guarded item updates: {path}')
